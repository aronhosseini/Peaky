#!/usr/bin/env python3
"""Single source of truth for the 20 factory presets.
Generates Source/FactoryPresets.inc (compiled in) and Presets/Factory/*.peakypreset (shareable files)."""
import os, re
# name, threshold, target, smoothing, maxGR(+dB), post, lookaheadOn, lookaheadIdx(0..5 = 5,10,15,20,30,50ms), detect(0 RMS/1 PEAK), mix%
P = [
 ("Natural Smoothing",   -10,-12,15, 8, 2,1,2,0,100),
 ("Gentle Leveler",       -8,-12,25, 4, 1,1,4,0,100),
 ("Pop Vocal Tamer",     -12,-12,12, 8, 2,1,2,1,100),
 ("Rap Peak Control",    -14,-14, 8,12, 3,1,1,1,100),
 ("Rock Vocal Taming",    -9,-10,10,10, 2,1,1,1,100),
 ("Intimate Whisper",    -18,-16,30, 6, 4,1,4,0,100),
 ("Plosive Softener",    -16,-14, 6,10, 0,1,1,1,100),
 ("Sibilant Peaks",      -14,-12, 5, 6, 0,1,0,1,100),
 ("Soft Ballad",         -11,-13,30, 5, 2,1,4,0,100),
 ("Broadcast Voice",     -12,-10,15,10, 2,1,2,0,100),
 ("Podcast Smooth",      -13,-13,20, 9, 3,1,3,0,100),
 ("Choir Blend",         -10,-14,40, 5, 1,1,5,0,100),
 ("Heavy Peak Flatten",  -18,-15,10,18, 4,1,1,1,100),
 ("Subtle Glue",          -6,-10,20, 3, 0,1,3,0,100),
 ("Pre-1176 Prep",       -10,-12,12, 8, 2,1,2,1,100),
 ("Pre-LA2A Prep",        -9,-12,30, 6, 2,1,4,0,100),
 ("Parallel Taming",     -14,-14,12,12, 3,1,2,1, 60),
 ("Fast Transient Catch",-12,-12, 5,10, 2,1,0,1,100),
 ("Wide Dynamic Singer",  -8,-10,18, 7, 1,1,3,0,100),
 ("Zero Latency Tamer",  -11,-12,10, 6, 2,0,0,1,100),
]
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
with open(os.path.join(root, "Source", "FactoryPresets.inc"), "w") as f:
    f.write("// Generated by tools/gen_presets.py - do not edit by hand\n")
    for n,*v in P:
        f.write('    { "%s", %.1ff, %.1ff, %.1ff, %.1ff, %.1ff, %d, %d, %d, %.1ff },\n' % (n, *v))
d = os.path.join(root, "Presets", "Factory"); os.makedirs(d, exist_ok=True)
keys = ["threshold","target","smoothing","maxgr","postgain","lookahead","lookaheadtime","detect","mix"]
for i,(n,*v) in enumerate(P,1):
    x = '<?xml version="1.0" encoding="UTF-8"?>\n<PeakyPreset name="%s" version="1">\n' % n
    x += "".join('  <Param id="%s" value="%s"/>\n' % (k, v[j]) for j,k in enumerate(keys))
    x += "</PeakyPreset>\n"
    open(os.path.join(d, "%02d - %s.peakypreset" % (i, re.sub(r'[^\w\- ]','',n))), "w").write(x)
print("wrote", len(P), "presets")
